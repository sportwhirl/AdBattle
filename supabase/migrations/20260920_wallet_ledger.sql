-- AdBattle wallet, 90/10 support ledger, and batched creator settlements.
--
-- Money rules implemented here:
--   * Supporters add at least $10 through Stripe Checkout.
--   * Wallet support can be any whole-cent amount, starting at $0.01.
--   * 90% accrues to the creator and 10% to AdBattle.
--   * Stripe charges the platform, so Stripe fees reduce AdBattle's share.
--   * Each ad settles at $10, $25, $50, $100, then doubling thresholds,
--     or after 24 hours without new support when at least $10 is pending.
--
-- Fractional creator/platform cents are stored as microdollars
-- (1 USD = 1,000,000 microdollars), so a $0.01 support splits exactly.

create extension if not exists pgcrypto;

-- ============================================================
-- WALLETS + TOP-UPS
-- ============================================================

create table if not exists public.wallets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  available_cents bigint not null default 0,
  lifetime_topup_cents bigint not null default 0 check (lifetime_topup_cents >= 0),
  lifetime_support_cents bigint not null default 0 check (lifetime_support_cents >= 0),
  status text not null default 'active' check (status in ('active', 'frozen')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.wallet_topups (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete restrict,
  stripe_session_id text not null unique,
  stripe_payment_intent_id text unique,
  amount_cents bigint not null check (amount_cents between 1000 and 1000000),
  status text not null default 'paid' check (status in ('paid', 'partially_refunded', 'refunded', 'disputed')),
  reversed_cents bigint not null default 0 check (reversed_cents >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (reversed_cents <= amount_cents)
);

create table if not exists public.wallet_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete restrict,
  entry_type text not null check (
    entry_type in ('topup', 'support_debit', 'refund', 'dispute', 'adjustment')
  ),
  amount_cents bigint not null check (amount_cents <> 0),
  balance_after_cents bigint not null,
  ad_id bigint references public.ads(id) on delete restrict,
  support_id bigint references public.supports(id) on delete restrict,
  topup_id bigint references public.wallet_topups(id) on delete restrict,
  request_id uuid,
  stripe_event_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create unique index if not exists wallet_transactions_request_id_uidx
on public.wallet_transactions (request_id)
where request_id is not null;

create unique index if not exists wallet_transactions_stripe_event_id_uidx
on public.wallet_transactions (stripe_event_id)
where stripe_event_id is not null;

create index if not exists wallet_transactions_user_created_idx
on public.wallet_transactions (user_id, created_at desc);

