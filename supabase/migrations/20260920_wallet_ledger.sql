alter table public.supports
add column if not exists source text not null default 'stripe_direct';

alter table public.supports
add column if not exists creator_share_percent numeric(5,2);

alter table public.supports
add column if not exists creator_amount numeric(18,6);

alter table public.supports
add column if not exists publishing_amount numeric(18,6);

alter table public.supports
add column if not exists platform_amount numeric(18,6);

alter table public.supports
add column if not exists promotion_allocation jsonb;

alter table public.supports
add column if not exists wallet_request_id uuid;

alter table public.supports
add column if not exists creator_amount_micros bigint;

alter table public.supports
add column if not exists platform_amount_micros bigint;

create unique index if not exists supports_wallet_request_id_uidx
on public.supports (wallet_request_id)
where wallet_request_id is not null;

do $$
declare
  constraint_row record;
begin
  -- Earlier AdBattle migrations required at least $0.50 per direct Stripe
  -- Support. Wallet Support starts at $0.01, so remove only amount checks
  -- that encode that old minimum before installing the new constraint.
  for constraint_row in
    select constraint_name.conname
    from pg_catalog.pg_constraint as constraint_name
    where constraint_name.conrelid = 'public.supports'::regclass
      and constraint_name.contype = 'c'
      and constraint_name.conkey @> array[
        (
          select attribute.attnum
          from pg_catalog.pg_attribute as attribute
          where attribute.attrelid = 'public.supports'::regclass
            and attribute.attname = 'amount'
        )
      ]::smallint[]
      and pg_catalog.pg_get_constraintdef(constraint_name.oid) ~* 'amount'
      and pg_catalog.pg_get_constraintdef(constraint_name.oid) ~* '(0[.]5|0[.]50|0[.]500)'
  loop
    execute format(
      'alter table public.supports drop constraint %I',
      constraint_row.conname
    );
  end loop;

  if not exists (
    select 1
    from pg_catalog.pg_constraint
    where conrelid = 'public.supports'::regclass
      and conname = 'supports_amount_at_least_one_cent'
  ) then
    alter table public.supports
      add constraint supports_amount_at_least_one_cent
      check (amount >= 0.01);
  end if;

  -- Wallet Support writes 90 explicitly. Keeping this column without a
  -- default prevents a legacy direct-Checkout completion during rollout
  -- from being mislabeled as a wallet-era 90/10 Support.
  alter table public.supports
    alter column creator_share_percent drop default;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name = 'supports'
      and column_name = 'creator_amount'
  ) then
    alter table public.supports
      alter column creator_amount type numeric(18,6)
      using creator_amount::numeric(18,6);
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name = 'supports'
      and column_name = 'platform_amount'
  ) then
    alter table public.supports
      alter column platform_amount type numeric(18,6)
      using platform_amount::numeric(18,6);
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name = 'supports'
      and column_name = 'publishing_amount'
  ) then
    alter table public.supports
      alter column publishing_amount type numeric(18,6)
      using publishing_amount::numeric(18,6);
  end if;
end
$$;

create or replace function public.next_adbattle_threshold_cents(
  p_lifetime_cents bigint
)
returns bigint
language plpgsql
immutable
set search_path = ''
as $$
declare
  threshold_cents bigint;
begin
  if coalesce(p_lifetime_cents, 0) < 1000 then return 1000; end if;
  if p_lifetime_cents < 2500 then return 2500; end if;
  if p_lifetime_cents < 5000 then return 5000; end if;
  if p_lifetime_cents < 10000 then return 10000; end if;

  threshold_cents := 20000;
  while threshold_cents <= p_lifetime_cents loop
    threshold_cents := threshold_cents * 2;
  end loop;

  return threshold_cents;
end;
$$;

