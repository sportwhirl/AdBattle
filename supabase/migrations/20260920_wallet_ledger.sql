  ) then
    alter table public.ad_settlement_state
      add constraint ad_settlement_state_active_settlement_fkey
      foreign key (active_settlement_id)
      references public.support_settlements(id)
      on delete restrict;
  end if;
end
$$;

create index if not exists ad_settlement_state_due_idx
on public.ad_settlement_state (last_support_at)
where active_settlement_id is null;

create index if not exists support_settlements_retry_idx
on public.support_settlements (next_attempt_at)
where status = 'retry';

-- Treat previously recorded Support as already settled. This prevents a
-- migration from paying historical direct-Checkout support a second time.
insert into public.ad_settlement_state (
  ad_id,
  creator_user_id,
  lifetime_support_cents,
  next_threshold_cents,
  last_settled_at
)
select
  ads.id,
  ads.user_id,
  round(coalesce(ads.support_total, 0) * 100)::bigint,
  public.next_adbattle_threshold_cents(
    round(coalesce(ads.support_total, 0) * 100)::bigint
  ),
  now()
from public.ads
on conflict (ad_id) do nothing;

-- ============================================================
-- ATOMIC WALLET TOP-UP
-- ============================================================

create or replace function public.record_wallet_topup(
  p_stripe_session_id text,
  p_stripe_payment_intent_id text,
  p_user_id uuid,
  p_amount_cents bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  inserted_topup_id bigint;
  existing_topup public.wallet_topups%rowtype;
  new_balance bigint;
begin
  if p_amount_cents < 1000 then
    raise exception 'TOPUP_BELOW_MINIMUM';
  end if;

  if p_amount_cents > 1000000 then
    raise exception 'TOPUP_ABOVE_MAXIMUM';
  end if;

  insert into public.wallet_topups (
    user_id,
    stripe_session_id,
    stripe_payment_intent_id,
    amount_cents
  ) values (
    p_user_id,
    p_stripe_session_id,
    nullif(p_stripe_payment_intent_id, ''),
    p_amount_cents
  )
  on conflict do nothing
  returning id into inserted_topup_id;

  if inserted_topup_id is null then
    select * into existing_topup
    from public.wallet_topups
    where stripe_session_id = p_stripe_session_id
      or (
        nullif(p_stripe_payment_intent_id, '') is not null
        and stripe_payment_intent_id = nullif(p_stripe_payment_intent_id, '')
      )
    limit 1;

    if not found
      or existing_topup.user_id <> p_user_id
      or existing_topup.amount_cents <> p_amount_cents
    then
      raise exception 'TOPUP_IDEMPOTENCY_CONFLICT';
    end if;

    select available_cents into new_balance
    from public.wallets
    where user_id = p_user_id;

    return jsonb_build_object(
      'credited', false,
      'balance_cents', coalesce(new_balance, 0)
    );
  end if;

  insert into public.wallets (
    user_id,
    available_cents,
    lifetime_topup_cents
  ) values (
    p_user_id,
    p_amount_cents,
    p_amount_cents
  )
  on conflict (user_id) do update
  set
    available_cents = public.wallets.available_cents + excluded.available_cents,
    lifetime_topup_cents = public.wallets.lifetime_topup_cents + excluded.lifetime_topup_cents,
    status = public.wallets.status,
    updated_at = now()
  returning available_cents into new_balance;

  insert into public.wallet_transactions (
    user_id,
    entry_type,
    amount_cents,
    balance_after_cents,
    topup_id,
    metadata
  ) values (
    p_user_id,
    'topup',
    p_amount_cents,
    new_balance,
    inserted_topup_id,
    jsonb_build_object('stripe_session_id', p_stripe_session_id)
  );

  return jsonb_build_object(
    'credited', true,
    'balance_cents', new_balance
  );
end;
$$;

-- ============================================================
-- ATOMIC SUPPORT FROM WALLET
-- ============================================================

create or replace function public.spend_wallet_support(
  p_user_id uuid,
  p_ad_id bigint,
  p_amount_cents bigint,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  wallet_row public.wallets%rowtype;
  ad_row public.ads%rowtype;
  existing_transaction public.wallet_transactions%rowtype;
  support_id bigint;
  balance_after bigint;
  previous_support_cents bigint;
  new_support_total_cents bigint;
  gross_micros bigint;
  creator_micros bigint;
  platform_micros bigint;
begin
  if p_request_id is null then
    raise exception 'INVALID_REQUEST_ID';
  end if;

  if p_amount_cents < 1 then
    raise exception 'SUPPORT_BELOW_MINIMUM';
  end if;

  select * into existing_transaction
  from public.wallet_transactions
  where request_id = p_request_id;

  if found then
    if existing_transaction.user_id <> p_user_id
      or existing_transaction.entry_type <> 'support_debit'
      or existing_transaction.ad_id is distinct from p_ad_id
      or existing_transaction.amount_cents <> -p_amount_cents
    then
      raise exception 'REQUEST_ID_CONFLICT';
    end if;

    return jsonb_build_object(
      'recorded', false,
      'balance_cents', existing_transaction.balance_after_cents,
      'support_id', existing_transaction.support_id
    );
  end if;

  select * into wallet_row
  from public.wallets
  where user_id = p_user_id
  for update;

  if not found then
    raise exception 'WALLET_NOT_FUNDED';
  end if;

  -- A concurrent retry can only pass the first idempotency check before this
  -- wallet row is locked. Check again after serialization.
  select * into existing_transaction
  from public.wallet_transactions
  where request_id = p_request_id;

  if found then
    if existing_transaction.user_id <> p_user_id
      or existing_transaction.entry_type <> 'support_debit'
      or existing_transaction.ad_id is distinct from p_ad_id
      or existing_transaction.amount_cents <> -p_amount_cents
    then
      raise exception 'REQUEST_ID_CONFLICT';
    end if;

    return jsonb_build_object(
      'recorded', false,
      'balance_cents', existing_transaction.balance_after_cents,
      'support_id', existing_transaction.support_id
    );
  end if;

  if wallet_row.status <> 'active' then
    raise exception 'WALLET_FROZEN';
  end if;

  if wallet_row.available_cents < p_amount_cents then
    raise exception 'INSUFFICIENT_WALLET_BALANCE';
  end if;

  select * into ad_row
  from public.ads
  where id = p_ad_id
  for update;

  if not found then
    raise exception 'AD_NOT_FOUND';
  end if;

  if ad_row.moderation_status <> 'approved' or ad_row.promotion_stopped_at is not null then
    raise exception 'AD_NOT_APPROVED';
  end if;

  previous_support_cents := round(coalesce(ad_row.support_total, 0) * 100)::bigint;
  new_support_total_cents := previous_support_cents + p_amount_cents;
  gross_micros := p_amount_cents * 10000;
  creator_micros := gross_micros * 90 / 100;
  platform_micros := gross_micros - creator_micros;

  insert into public.supports (
    user_id,
    ad_id,
    amount,
    stripe_session_id,
    stripe_payment_intent_id,
    creator_share_percent,
    creator_amount,
    publishing_amount,
    platform_amount,
    source,
    wallet_request_id,
    creator_amount_micros,
    platform_amount_micros,
    promotion_allocation
  ) values (
    p_user_id,
    p_ad_id,
    p_amount_cents::numeric / 100,
    'wallet:' || p_request_id::text,
    'wallet:' || p_request_id::text,
    90,
    creator_micros::numeric / 1000000,
    0,
    platform_micros::numeric / 1000000,
    'wallet',
    p_request_id,
    creator_micros,
    platform_micros,
    coalesce(ad_row.promotion_allocation, '{}'::jsonb)
  )
  returning id into support_id;

  update public.wallets
  set
    available_cents = available_cents - p_amount_cents,
    lifetime_support_cents = lifetime_support_cents + p_amount_cents,
    updated_at = now()
  where user_id = p_user_id
  returning available_cents into balance_after;

  update public.ads
  set support_total = new_support_total_cents::numeric / 100
  where id = p_ad_id;

  insert into public.ad_settlement_state (
    ad_id,
    creator_user_id,
    lifetime_support_cents,
    pending_creator_micros,
    pending_platform_micros,
    next_threshold_cents,
    last_support_at
  ) values (
    p_ad_id,
    ad_row.user_id,
    new_support_total_cents,
    creator_micros,
    platform_micros,
    public.next_adbattle_threshold_cents(previous_support_cents),
    now()
  )
  on conflict (ad_id) do update
  set
    creator_user_id = excluded.creator_user_id,
    lifetime_support_cents = excluded.lifetime_support_cents,
    pending_creator_micros = public.ad_settlement_state.pending_creator_micros + creator_micros,
    pending_platform_micros = public.ad_settlement_state.pending_platform_micros + platform_micros,
    last_support_at = now(),
    updated_at = now();

  insert into public.wallet_transactions (
    user_id,
    entry_type,
    amount_cents,
    balance_after_cents,
    ad_id,
    support_id,
    request_id,
    metadata
  ) values (
    p_user_id,
    'support_debit',
    -p_amount_cents,
    balance_after,
    p_ad_id,
    support_id,
    p_request_id,
    jsonb_build_object(
      'creator_micros', creator_micros,
      'platform_micros', platform_micros
    )
  );

  return jsonb_build_object(
    'recorded', true,
    'balance_cents', balance_after,
    'support_id', support_id,
    'support_total_cents', new_support_total_cents,
    'creator_micros', creator_micros,
    'platform_micros', platform_micros
  );
end;
$$;

-- ============================================================
-- SETTLEMENT CLAIM / RETRY / COMPLETION
-- ============================================================

create or replace function public.claim_due_wallet_settlements(
  p_limit integer default 25
)
returns table (
  settlement_id uuid,
  ad_id bigint,
  creator_user_id uuid,
  stripe_account_id text,
  creator_transfer_cents bigint,
  creator_micros bigint,
  platform_micros bigint,
  trigger_reason text
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  candidate record;
  new_settlement_id uuid;
  returned_count integer := 0;
begin
  -- Retry the same settlement ID so Stripe's idempotency key remains stable.
  for candidate in
    select
      settlements.id,
      settlements.ad_id,
      settlements.creator_user_id,
      settlements.creator_transfer_cents,
      settlements.creator_micros,
      settlements.platform_micros,
      settlements.trigger_reason,
      accounts.stripe_account_id
    from public.support_settlements as settlements
    join public.ad_settlement_state as state
      on state.active_settlement_id = settlements.id
    join public.creator_accounts as accounts
      on accounts.user_id = settlements.creator_user_id
    where (
        (
          settlements.status = 'retry'
          and settlements.next_attempt_at <= now()
        ) or (
          settlements.status = 'processing'
          and settlements.updated_at <= now() - interval '15 minutes'
        )
      )
      and accounts.stripe_account_id is not null
      and accounts.onboarding_complete = true
      and accounts.charges_enabled = true
      and accounts.payouts_enabled = true
    order by settlements.next_attempt_at
    limit greatest(1, least(coalesce(p_limit, 25), 100))
    for update of settlements skip locked
  loop
    update public.support_settlements
    set
      status = 'processing',
      attempts = attempts + 1,
      updated_at = now()
    where id = candidate.id;

    settlement_id := candidate.id;
    ad_id := candidate.ad_id;
    creator_user_id := candidate.creator_user_id;
    stripe_account_id := candidate.stripe_account_id;
    creator_transfer_cents := candidate.creator_transfer_cents;
    creator_micros := candidate.creator_micros;
    platform_micros := candidate.platform_micros;
    trigger_reason := candidate.trigger_reason;
    returned_count := returned_count + 1;
    return next;
  end loop;

  if returned_count >= greatest(1, least(coalesce(p_limit, 25), 100)) then
    return;
  end if;

  for candidate in
    select
      state.*,
      accounts.stripe_account_id,
      case
        when state.lifetime_support_cents >= state.next_threshold_cents then 'threshold'
        else 'inactivity'
      end as reason
    from public.ad_settlement_state as state
    join public.creator_accounts as accounts
      on accounts.user_id = state.creator_user_id
    where state.active_settlement_id is null
      and state.pending_creator_micros >= 10000
      and (
        state.lifetime_support_cents >= state.next_threshold_cents
        or (
          state.pending_creator_micros + state.pending_platform_micros >= 10000000
          and state.last_support_at <= now() - interval '24 hours'
        )
      )
      and accounts.stripe_account_id is not null
      and accounts.onboarding_complete = true
      and accounts.charges_enabled = true
      and accounts.payouts_enabled = true
    order by state.last_support_at
    limit greatest(0, greatest(1, least(coalesce(p_limit, 25), 100)) - returned_count)
    for update of state skip locked
  loop
    new_settlement_id := gen_random_uuid();

    insert into public.support_settlements (
      id,
      ad_id,
      creator_user_id,
      trigger_reason,
      gross_micros,
      creator_micros,
      platform_micros,
      creator_transfer_cents,
      support_total_cents_snapshot,
      threshold_cents_snapshot
    ) values (
      new_settlement_id,
      candidate.ad_id,
      candidate.creator_user_id,
      candidate.reason,
      candidate.pending_creator_micros + candidate.pending_platform_micros,
      candidate.pending_creator_micros,
      candidate.pending_platform_micros,
      floor(candidate.pending_creator_micros::numeric / 10000)::bigint,
      candidate.lifetime_support_cents,
      candidate.next_threshold_cents
    );

    update public.ad_settlement_state
    set
      active_settlement_id = new_settlement_id,
      updated_at = now()
    where ad_settlement_state.ad_id = candidate.ad_id;

    settlement_id := new_settlement_id;
    ad_id := candidate.ad_id;
    creator_user_id := candidate.creator_user_id;
    stripe_account_id := candidate.stripe_account_id;
    creator_transfer_cents := floor(candidate.pending_creator_micros::numeric / 10000)::bigint;
    creator_micros := candidate.pending_creator_micros;
    platform_micros := candidate.pending_platform_micros;
    trigger_reason := candidate.reason;
    return next;
  end loop;
end;
$$;

create or replace function public.retry_wallet_settlement(
  p_settlement_id uuid,
  p_error text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.support_settlements
  set
    status = 'retry',
    next_attempt_at = now() + interval '5 minutes',
    last_error = left(coalesce(p_error, 'Unknown transfer error'), 1000),
    updated_at = now()
  where id = p_settlement_id
    and status <> 'succeeded';
end;
$$;

create or replace function public.complete_wallet_settlement(
  p_settlement_id uuid,
  p_stripe_transfer_id text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  settlement_row public.support_settlements%rowtype;
  state_row public.ad_settlement_state%rowtype;
  transferred_creator_micros bigint;
begin
  select * into settlement_row
  from public.support_settlements
  where id = p_settlement_id
  for update;

  if not found then
    raise exception 'SETTLEMENT_NOT_FOUND';
  end if;

  if settlement_row.status = 'succeeded' then
    return false;
  end if;

  select * into state_row
  from public.ad_settlement_state
  where ad_id = settlement_row.ad_id
  for update;

  if state_row.active_settlement_id is distinct from settlement_row.id then
    raise exception 'SETTLEMENT_STATE_MISMATCH';
  end if;

  transferred_creator_micros := settlement_row.creator_transfer_cents * 10000;

  if state_row.pending_creator_micros < transferred_creator_micros
    or state_row.pending_platform_micros < settlement_row.platform_micros
  then
    raise exception 'SETTLEMENT_BALANCE_MISMATCH';
  end if;

  update public.ad_settlement_state
  set
    pending_creator_micros = pending_creator_micros - transferred_creator_micros,
    pending_platform_micros = pending_platform_micros - settlement_row.platform_micros,
    next_threshold_cents = public.next_adbattle_threshold_cents(
      settlement_row.support_total_cents_snapshot
    ),
    last_settled_at = now(),
    active_settlement_id = null,
    updated_at = now()
  where ad_id = settlement_row.ad_id;

  update public.support_settlements
  set
    stripe_transfer_id = p_stripe_transfer_id,
    status = 'succeeded',
    next_attempt_at = null,
    last_error = null,
    completed_at = now(),
    updated_at = now()
  where id = p_settlement_id;

  return true;
end;
$$;

