create or replace function public.get_public_ads()
returns table(
  id bigint,
  user_id uuid,
  title text,
  caption text,
  image_url text,
  support_total numeric,
  created_at timestamptz,
  moderation_status text
) language sql stable security definer set search_path = '' as $$
  select a.id,a.user_id,a.title,a.caption,a.image_url,a.support_total,
    a.created_at,a.moderation_status
  from public.ads a
  where a.moderation_status='approved'
  order by a.created_at desc,a.id desc
$$;

