-- Duplicate-image screening and creator attribution. This migration only
-- prepares data structures/functions; it does not enable storage or deploy a scanner.
begin;

alter table public.ads
  add column if not exists image_storage_path text,
  add column if not exists moderation_details jsonb,
  add column if not exists moderation_risk_score integer,
  add column if not exists moderation_scan_version text,
  add column if not exists moderation_image_sha256 text,
  add column if not exists moderation_last_error text,
  add column if not exists moderation_attempts integer not null default 0,
  add column if not exists moderation_last_attempt_at timestamptz,
  add column if not exists safety_status text,
  add column if not exists duplicate_status text,
  add column if not exists duplicate_of_ad_id bigint references public.ads(id) on delete set null,
  add column if not exists image_index_required boolean;

update public.ads set
  safety_status = case when moderation_status = 'approved' then 'passed'
    when moderation_status in ('rejected','removed') then 'failed' else 'pending' end,
  duplicate_status = case when moderation_status = 'approved' then 'passed' else 'pending' end,
  image_index_required = true
where safety_status is null or duplicate_status is null or image_index_required is null;

alter table public.ads
  alter column safety_status set default 'pending',
  alter column safety_status set not null,
  alter column duplicate_status set default 'pending',
  alter column duplicate_status set not null,
  alter column image_index_required set default false,
  alter column image_index_required set not null,
  add constraint ads_safety_status_valid check (safety_status in ('pending','passed','held','failed')),
  add constraint ads_duplicate_status_valid check (duplicate_status in
    ('pending','passed','review_identical','review_similar','duplicate_same_creator','rejected'));

-- Append-only audit data restored from the deployed safety scanner v2 schema.
create table if not exists public.moderation_events (
  id bigint generated by default as identity primary key,
  ad_id bigint not null references public.ads(id) on delete restrict,
  stage text not null,
  outcome text not null,
  reason text,
  details jsonb,
  created_at timestamptz not null default now()
);
create index if not exists moderation_events_ad_id_idx
  on public.moderation_events(ad_id,created_at desc);
create index if not exists ads_moderation_image_sha256_idx
  on public.ads(moderation_image_sha256) where moderation_image_sha256 is not null;
alter table public.moderation_events enable row level security;
revoke all on public.moderation_events from public,anon,authenticated;
grant all on public.moderation_events to service_role;
revoke update (moderation_status,moderation_reason,moderation_details,
  moderation_risk_score,moderation_scan_version,moderation_image_sha256,
  moderation_last_error,moderation_attempts,moderation_last_attempt_at,
  moderated_at,promotion_stopped_at) on public.ads from anon,authenticated;

create table public.ad_image_fingerprints (
  ad_id bigint primary key references public.ads(id) on delete cascade,
  sha256 bytea not null check (octet_length(sha256) = 32),
  visual_hash bit(64) not null,
  visual_hash_version text not null,
  scanned_at timestamptz not null default now()
);
create index ad_image_fingerprints_sha256_idx on public.ad_image_fingerprints(sha256);
create index ads_duplicate_review_idx on public.ads(duplicate_status)
  where duplicate_status in ('review_identical','review_similar');

create table public.ad_scan_attempts (
  id bigint generated always as identity primary key,
  ad_id bigint not null references public.ads(id) on delete cascade,
  outcome text not null check (outcome in ('completed','failed','legacy_indexed')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.ad_duplicate_review_decisions (
  id bigint generated always as identity primary key,
  ad_id bigint not null unique references public.ads(id) on delete restrict,
  matched_ad_id bigint not null references public.ads(id) on delete restrict,
  previous_duplicate_status text not null check (
    previous_duplicate_status in ('review_identical','review_similar')
  ),
  decision text not null check (decision in ('clear','reject')),
  reviewer_identity text not null check (length(trim(reviewer_identity)) >= 3),
  reason text not null check (length(trim(reason)) >= 10),
  created_at timestamptz not null default now()
);

create table public.ad_image_index_state (
  singleton boolean primary key default true check (singleton),
  ready boolean not null default false,
  completed_at timestamptz,
  notes text
);
insert into public.ad_image_index_state(singleton,ready,notes)
  values(true,false,'Existing-image backfill has not been verified');

create table public.ad_image_index_exceptions (
  ad_id bigint primary key references public.ads(id) on delete cascade,
  reason text not null check (length(trim(reason)) >= 10),
  reviewed_by text not null check (length(trim(reviewed_by)) >= 3),
  reviewed_at timestamptz not null default now()
);

-- The supplied schema has no creator display-name field. Add a narrowly scoped,
-- owner-maintained profile rather than deriving a public name from email/auth data.
